export function message(code, language = 'en', params = {}) {
  const text = messages[language === 'ja' ? 'ja' : 'en'][code];
  return text.replace(/\{(\w+)\}/g, (_, key) => params[key]);
}

export function localizedError(code, params = {}) {
  return Object.assign(new Error(message(code, 'en', params)), { code, params });
}

export function errorMessage(error, language = 'en') {
  return Object.hasOwn(messages.en, error.code) ? message(error.code, language, error.params) : error.message;
}
